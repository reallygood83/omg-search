  async buildSyncedNotesContext() {
    const contexts = [];
    let totalLength = 0;
    const maxTotalLength = 24e3;
    for (const path in this.plugin.settings.files) {
      const syncData = this.plugin.settings.files[path];
      if (syncData.status !== "synced")
        continue;
      if (!this.plugin.isInSyncFolder(path))
        continue;
      const file = this.plugin.app.vault.getAbstractFileByPath(path);
      if (!(file instanceof import_obsidian5.TFile) || file.extension !== "md")
        continue;
      try {
        const content = await this.plugin.app.vault.read(file);
        const truncated = content.length > 1800 ? `${content.slice(0, 1800)}...[truncated]` : content;
        const block = `--- ${file.path} ---
${truncated}
`;
        if (totalLength + block.length > maxTotalLength)
          break;
        contexts.push(block);
        totalLength += block.length;
      } catch (error) {
        console.warn(`Failed to read synced note for Agent context: ${path}`, error);
      }
    }
    return contexts.join("\n") || "No synced notes are available in the selected sync folders.";
  }
  exec(command, args, logPath, onChunk) {
    return new Promise((resolve, reject) => {
      var _a, _b, _c;
      let stdout = "";
      let stderr = "";
      let settled = false;
      const maxBuffer = 1024 * 1024 * 8;
      const timeoutMs = Math.max(3e4, this.plugin.settings.agentTimeoutSeconds * 1e3);
      const child = (0, import_child_process.spawn)(command, args, {
        cwd: this.plugin.getVaultPath(),
        env: {
          ...process.env,
          ...this.parseEnv(this.plugin.settings.agentEnvironment)
        },
        shell: process.platform === "win32" && /\.(cmd|bat)$/i.test(command),
        windowsHide: true
      });
      this.activeChild = child;
      void this.appendAgentLog(logPath, {
        event: "spawn",
        pid: (_a = child.pid) != null ? _a : null
      });
      const timer = window.setTimeout(() => {
        settled = true;
        child.kill();
        if (this.activeChild === child)
          this.activeChild = null;
        void this.appendAgentLog(logPath, {
          event: "timeout",
          timeoutMs,
          stdoutLength: stdout.length,
          stderrLength: stderr.length
        });
        reject(Object.assign(new Error(`Agent timed out after ${Math.round(timeoutMs / 1e3)}s`), {
          code: "ETIMEDOUT",
          stdout,
          stderr
        }));
      }, timeoutMs);
      (_b = child.stdout) == null ? void 0 : _b.on("data", (data) => {
        const chunk = data.toString();
        stdout += chunk;
        onChunk == null ? void 0 : onChunk(chunk, "stdout");
        void this.appendAgentLog(logPath, { event: "stdout", chunk });
        if (stdout.length + stderr.length > maxBuffer) {
          void this.appendAgentLog(logPath, { event: "max_buffer", maxBuffer });
          child.kill();
        }
      });
      (_c = child.stderr) == null ? void 0 : _c.on("data", (data) => {
        const chunk = data.toString();
        stderr += chunk;
        onChunk == null ? void 0 : onChunk(chunk, "stderr");
        void this.appendAgentLog(logPath, { event: "stderr", chunk });
        if (stdout.length + stderr.length > maxBuffer) {
          void this.appendAgentLog(logPath, { event: "max_buffer", maxBuffer });
          child.kill();
        }
      });
      child.on("error", (error) => {
        if (settled)
          return;
        settled = true;
        if (this.activeChild === child)
          this.activeChild = null;
        window.clearTimeout(timer);
        void this.appendAgentLog(logPath, {
          event: "error",
          message: error.message,
          stdoutLength: stdout.length,
          stderrLength: stderr.length
        });
        if (this.stopWasRequested) {
          this.stopWasRequested = false;
          reject(Object.assign(new Error("Agent run stopped by user."), {
            code: "EAGENTSTOPPED",
            stdout,
            stderr
          }));
          return;
        }
        reject(Object.assign(error, { stdout, stderr }));
      });
      child.on("close", (code) => {
        if (settled)
          return;
        settled = true;
        if (this.activeChild === child)
          this.activeChild = null;
        window.clearTimeout(timer);
        void this.appendAgentLog(logPath, {
          event: "close",
          exitCode: code,
          stdoutLength: stdout.length,
          stderrLength: stderr.length
        });
        if (this.stopWasRequested) {
          this.stopWasRequested = false;
          reject(Object.assign(new Error("Agent run stopped by user."), {
            code: "EAGENTSTOPPED",
            stdout,
            stderr
          }));
          return;
        }
        if (code === 0) {
          resolve({ stdout, stderr });
          return;
        }
        reject(Object.assign(new Error(`Agent exited with code ${code != null ? code : "unknown"}`), {
          code,
          stdout,
          stderr
        }));
      });
    });
  }
